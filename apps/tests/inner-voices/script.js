const STORAGE_KEY='innerVoices:lastResult:v2';
const $=id=>document.getElementById(id);
let current=0;
let answers=Array(questions.length).fill(null);
let transitionTimer=null;
let transitioning=false;

function readLastResult(){try{const value=JSON.parse(localStorage.getItem(STORAGE_KEY));return value&&Array.isArray(value.scores)&&profiles[value.type]?value:null}catch{return null}}
function updateLastResultButton(){const hasResult=Boolean(readLastResult());$('lastResultBtn').disabled=!hasResult;$('lastResultBtn').title=hasResult?'查看本浏览器最近一次完成的测试':'完成一次测试后即可查看'}
function hideAll(){['intro','quiz','result'].forEach(id=>$(id).classList.add('hidden'));document.querySelector('.principles').classList.add('hidden')}
function start(){clearTimeout(transitionTimer);transitioning=false;hideAll();$('quiz').classList.remove('hidden');render();window.scrollTo({top:0,behavior:'smooth'})}
function render(){
  const q=questions[current],total=questions.length;
  $('qIndexLabel').textContent=String(current+1).padStart(2,'0');
  $('progressText').textContent=`${current+1} / ${total}`;
  $('progressBar').style.width=`${((current+1)/total)*100}%`;
  $('questionKicker').textContent=`SCENE ${String(current+1).padStart(2,'0')}`;
  $('questionText').textContent=q[0];
  $('sectionTitle').textContent=current<16?'你的第一反应':current<32?'你与世界的相处方式':'听见内心的回声';
  $('options').innerHTML=q.slice(1).map((option,index)=>`<button class="option ${answers[current]===index?'selected':''}" data-index="${index}" type="button"><b>${String.fromCharCode(65+index)}</b><span>${option}</span></button>`).join('');
  document.querySelectorAll('.option').forEach(button=>button.addEventListener('click',()=>selectAnswer(Number(button.dataset.index))));
  $('prevBtn').disabled=current===0;
}
function selectAnswer(index){
  if(transitioning)return;
  answers[current]=index;
  transitioning=true;
  document.querySelectorAll('.option').forEach((button,i)=>{button.classList.toggle('selected',i===index);button.classList.add('locked')});
  transitionTimer=setTimeout(()=>{
    transitioning=false;
    if(current<questions.length-1){current+=1;render();window.scrollTo({top:0,behavior:'smooth'})}
    else completeTest();
  },320);
}
function goPrevious(){
  clearTimeout(transitionTimer);transitioning=false;
  if(current>0){current-=1;render();window.scrollTo({top:0,behavior:'smooth'})}
}
function calculatePercentages(scores){const first=Math.round(scores[0]/questions.length*100);const second=Math.round(scores[1]/questions.length*100);return[first,second,100-first-second]}
function classify(scores){
  const order=[0,1,2].sort((a,b)=>scores[b]-scores[a]);
  const spread=scores[order[0]]-scores[order[2]],lead=scores[order[0]]-scores[order[1]],lowerGap=scores[order[1]]-scores[order[2]];
  if(spread<=2)return'balanced';
  if(lead>=5)return['id','ego','superego'][order[0]];
  if(lowerGap<=2)return'adaptive';
  return {'0,1':'idEgo','0,2':'idSuperego','1,2':'egoSuperego'}[[order[0],order[1]].sort((a,b)=>a-b).join(',')];
}
function completeTest(){
  const scores=[0,0,0];answers.forEach(answer=>scores[answer]++);
  const result={scores,type:classify(scores),completedAt:new Date().toISOString()};
  try{localStorage.setItem(STORAGE_KEY,JSON.stringify(result))}catch{}
  updateLastResultButton();showResult(result);
}
function showResult(result){
  const {scores,type}=result,p=profiles[type],perc=calculatePercentages(scores);
  hideAll();$('result').classList.remove('hidden');
  $('resultTitle').textContent=p.title;$('resultSummary').textContent=p.summary;$('resultSymbol').textContent=p.symbol;
  ['id','ego','superego'].forEach((key,index)=>{$(key+'Score').textContent=perc[index]+'%';$(key+'Bar').style.width=perc[index]+'%'});
  $('resultDetail').innerHTML=p.detail.map(([title,text])=>`<section class="detail-block"><h4>${title}</h4><p>${text}</p></section>`).join('');
  $('resultQuote').textContent=p.quote;$('resultPractice').textContent=p.practice;
  window.scrollTo({top:0,behavior:'smooth'});
}
function restart(){clearTimeout(transitionTimer);transitioning=false;current=0;answers=Array(questions.length).fill(null);start()}

