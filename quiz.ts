export function scoreAnswers(answers: number[]) {
  if (
    !Array.isArray(answers) ||
    answers.length !== questions.length ||
    questions.some(
      (_, i) =>
        !Number.isInteger(answers[i]) || answers[i] < 0 || answers[i] > 3,
    )
  )
    throw new Error("请完成全部16道题，每题选择一个有效选项。");
  const vector = dimensions.map(
    (_, d) =>
      questions.reduce(
        (sum, q, i) => sum + (q.dimension === d ? q.values[answers[i]] : 0),
        0,
      ) / 4,
  );
  const matches = characters
    .map((character, index) => ({
      character,
      index,
      distance: Math.sqrt(
        character.vector.reduce((sum, v, d) => sum + (vector[d] - v) ** 2, 0) /
          4,
      ),
    }))
    .sort((a, b) => a.distance - b.distance || a.index - b.index)
    .map((m) => ({
      ...m,
      score: Math.max(0, Math.round((1 - m.distance / 6) * 100)),
    }));
  return { vector, matches };
}
export function dimensionText(d: number, value: number) {
  return value > 0.5
    ? dimensions[d].positive
    : value < -0.5
      ? dimensions[d].negative
      : dimensions[d].balanced;
}
export function evidenceFor(answers: number[], character: Character) {
  return questions
    .map((q, i) => ({
      question: q,
      answer: q.options[answers[i]],
      closeness: Math.abs(q.values[answers[i]] - character.vector[q.dimension]),
    }))
    .sort((a, b) => a.closeness - b.closeness)
    .filter(
      (x, i, all) =>
        all.findIndex((v) => v.question.dimension === x.question.dimension) ===
        i,
    )
    .slice(0, 3);
}
